"""Generate one native SQL-runner case with an observed Iceberg manifest count.

Each positive source append and MV refresh produces one target manifest under
the current writer. Negative rows advance only the source and MV watermark,
but their publications can add manifests. Spark checks the exact starting
count and records the final count, so the declared scale is observed rather
than inferred from the number of writes.
"""

from __future__ import annotations

import argparse
from pathlib import Path


CATALOG_SQL = """CREATE EXTERNAL CATALOG mvscale_${uuid0}
PROPERTIES (
  "type" = "iceberg",
  "iceberg.catalog.type" = "rest",
  "uri" = "${iceberg_rest_uri}",
  "warehouse" = "${iceberg_rest_warehouse}",
  "credential.object-store-metadata.consumer-role" = "frontend",
  "credential.object-store-metadata.mode" = "static",
  "credential.object-store-metadata.name" = "${iceberg_object_store_credential_name}",
  "credential.object-store-metadata.generation" = "${iceberg_object_store_credential_generation}",
  "credential.object-store-data.consumer-role" = "backend",
  "credential.object-store-data.mode" = "static",
  "credential.object-store-data.name" = "${iceberg_object_store_credential_name}",
  "credential.object-store-data.generation" = "${iceberg_object_store_credential_generation}",
  "aws.s3.endpoint" = "${oss_endpoint}",
  "aws.s3.region" = "us-east-1",
  "aws.s3.enable_path_style_access" = "true"
);"""


def case(manifests: int, metadata_publications: int, measure_rest_traffic: bool = False) -> str:
    if manifests < 0 or metadata_publications < 0:
        raise ValueError("publication counts must be nonnegative")
    lines = [
        "-- @sequential=true",
        "-- @tags=mv,iceberg,rest,minio,scale",
        "-- Generated by tools/benchmark/mv-persistence/generate-scale-sql.py.",
    ]
    step = 0

    def add(sql: str, *, cleanup: bool = False, contains: str | None = None) -> None:
        nonlocal step
        step += 1
        lines.extend(("", f"-- query {step}"))
        if cleanup:
            lines.append("-- @cleanup=true")
        if contains is None:
            lines.append("-- @skip_result_check=true")
        else:
            lines.append(f"-- @result_contains={contains}")
        lines.append(sql)

    add(CATALOG_SQL)
    add("CREATE DATABASE mvscale_${uuid0}.ns_${uuid0};")
    add(
        "CREATE TABLE mvscale_${uuid0}.ns_${uuid0}.fact "
        '(k STRING, v BIGINT) TBLPROPERTIES '
        '("format-version" = "3", "write.row-lineage" = "true");'
    )
    add(
        "SET CATALOG mvscale_${uuid0};\n"
        "USE ns_${uuid0};\n"
        "CREATE MATERIALIZED VIEW mv\n"
        "DISTRIBUTED BY HASH(k) BUCKETS 1\n"
        "REFRESH DEFERRED MANUAL\n"
        "PROPERTIES ('storage_engine' = 'iceberg')\n"
        "AS SELECT k, v FROM fact WHERE v >= 0;"
    )
    for index in range(manifests):
        add(f"INSERT INTO fact VALUES ('positive_{index}', {index});")
        add("REFRESH MATERIALIZED VIEW mv WITH SYNC MODE;")

    def spark_count(phase: str, expected: int | None) -> str:
        if expected is None:
            check = (
                'count=$(grep -E "^[0-9]+$" "$output"); '
                'case "$count" in ""|*[!0-9]*) cat "$output"; '
                'echo "invalid final MV manifest count" >&2; exit 1;; esac; '
            )
        else:
            check = (
                'count=$(grep -E "^[0-9]+$" "$output"); '
                f'test "$count" = {expected} || '
                '{ cat "$output"; echo "unexpected starting MV manifest count" >&2; exit 1; }; '
            )
        value = str(expected) if expected is not None else "$count"
        artifact_check = (
            'test ! -e "$UEA7_SCALE_OBSERVATION_FILE"; '
            if phase == "BEFORE"
            else 'test -f "$UEA7_SCALE_OBSERVATION_FILE"; '
        )
        artifact_redirect = ">" if phase == "BEFORE" else ">>"
        return (
            "shell: set -eu; "
            'query=$(mktemp "${TMPDIR:-/tmp}/uea7-scale-spark-XXXXXX.sql"); '
            'output=$(mktemp "${TMPDIR:-/tmp}/uea7-scale-spark-XXXXXX.out"); '
            'trap \'rm -f "$query" "$output"\' EXIT; '
            "printf '%s\\n' 'SELECT count(*) FROM ice_rest.ns_${uuid0}.mv.manifests;' > \"$query\"; "
            '"${NOVAROCKS_WORKSPACE_ROOT:-.}/docker/iceberg-rest/spark-sql.sh" '
            '"$query" > "$output" 2>&1; '
            + check
            + f'echo MV_MANIFEST_COUNT_{phase}={value}; '
            + f'if test -n "${{UEA7_SCALE_OBSERVATION_FILE:-}}"; then '
            + artifact_check
            + f'echo MV_MANIFEST_COUNT_{phase}={value} {artifact_redirect} "$UEA7_SCALE_OBSERVATION_FILE"; fi'
        )

    add(spark_count("BEFORE", manifests), contains=f"MV_MANIFEST_COUNT_BEFORE={manifests}")

    def traffic(phase: str, index: int) -> str:
        return (
            "shell: set -eu; "
            'test -n "${UEA7_SCALE_REST_TRAFFIC_FILE:-}"; '
            'python3 "${NOVAROCKS_WORKSPACE_ROOT:-.}/tools/benchmark/mv-persistence/'
            'record-rest-traffic.py" '
            "--uri '${iceberg_rest_uri}' "
            '--artifact "$UEA7_SCALE_REST_TRAFFIC_FILE" '
            f"--phase {phase} --index {index}; "
            f"echo REST_TRAFFIC_{phase.upper()}={index}"
        )

    for index in range(metadata_publications):
        add(f"INSERT INTO fact VALUES ('negative_{index}', -{index + 1});")
        if measure_rest_traffic:
            add(traffic("before", index), contains=f"REST_TRAFFIC_BEFORE={index}")
        add("REFRESH MATERIALIZED VIEW mv WITH SYNC MODE;")
        if measure_rest_traffic:
            add(traffic("after", index), contains=f"REST_TRAFFIC_AFTER={index}")
    add(spark_count("AFTER", None), contains="MV_MANIFEST_COUNT_AFTER=")
    add("SELECT count(*) FROM mv;", contains=str(manifests))
    add(
        "DROP MATERIALIZED VIEW mv;\n"
        "DROP TABLE mvscale_${uuid0}.ns_${uuid0}.fact FORCE;\n"
        "DROP DATABASE mvscale_${uuid0}.ns_${uuid0};\n"
        "DROP CATALOG mvscale_${uuid0};",
        cleanup=True,
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifests", type=int, choices=(0, 1, 100, 1000), required=True)
    parser.add_argument("--metadata-publications", type=int, default=1000)
    parser.add_argument("--measure-rest-traffic", action="store_true")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    if args.metadata_publications < 0:
        parser.error("--metadata-publications must be nonnegative")
    if args.output.exists():
        parser.error(f"output already exists: {args.output}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        case(args.manifests, args.metadata_publications, args.measure_rest_traffic),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
